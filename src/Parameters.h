    auto route = [&] (const char* id, const char* name, int def) { p.push_back (std::make_unique<C> (pid (id), name, StringArray { "Off", "Direct", "Wheel" }, def)); };

    auto logr = [&] (const char* id, const char* name, float lo, float hi, float centre, float def) { NormalisableRange<float> r (lo, hi); r.setSkewForCentre (centre); p.push_back (std::make_unique<F> (pid (id), name, r, def)); };
    auto ch = [&] (const char* id, const char* name, StringArray opts, int def) { p.push_back (std::make_unique<C> (pid (id), name, opts, def)); };
    auto it = [&] (const char* id, const char* name, int lo, int hi, int def) { p.push_back (std::make_unique<AudioParameterInt> (pid (id), name, lo, hi, def)); };
